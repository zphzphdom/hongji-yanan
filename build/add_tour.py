# 把每处 party=dict(script="...", questions=[...]) 替换为带 tour 的结构
count = 0
for pid, segs in TOURS.items():
    # 定位该点位块里的 party=dict(
    block_start = s.find('id="%s"' % pid)
    if block_start < 0:
        print("未找到点位", pid)
        continue
    ps = s.find("party=dict(", block_start)
    if ps < 0:
        print("未找到 party 段", pid)
        continue
    script_start = s.find('script="', ps)
    script_end = s.find('questions=[', ps)
    if script_start < 0 or script_end < 0:
        print("讲稿区间异常", pid)
        continue
    tour_lit = "tour=[" + ", ".join('("%s", "%s")' % (t, b) for t, b in segs) + "],\n            "
    s = s[:script_start] + tour_lit + s[script_start:]
    count += 1

io.open(P, "w", encoding="utf-8").write(s)
