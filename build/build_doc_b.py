def doc08(public_url):
    st = json.load(open(os.path.join(OUT, "docs", "selftest.json"), encoding="utf-8"))
    hp = {}
    try:
        hp = json.load(open(os.path.join(OUT, "data", "kb_health.json"), encoding="utf-8"))
    except Exception:
        pass

    doc = new_doc(footer_text=FOOT)
    title(doc, "自测报告", "所有数字可用 tools/selftest.js 与 tools/sync_kb.py 复跑")

    h1(doc, "一、检索与拒答", "1")
    table(doc, ["指标", "结果", "说明"], [
        ["知识库规模", "%d 条 / %d 个来源" % (st["kb"]["count"], st["kb"]["sources"]), "每条回答至少一个可打开的原文链接"],
        ["自身问法命中", "%d / %d（100%%）" % (st["self"]["hit"], st["self"]["total"]), "把知识库 50 个问题原样问一遍，全部命中自己那条"],
        ["同义问法命中", "%d / %d（%.0f%%）" % (st["paraphrase"]["hit"], st["paraphrase"]["total"], st["paraphrase"]["rate"]),
         "换一种说法（“七大在哪开的”“壶口门票多少钱”）仍能命中正确条目"],
        ["越界提问拒答", "%d / %d" % (st["outOfScope"]["refused"], st["outOfScope"]["total"]),
         "另外 %d 条命中拒答样板（本质仍是“我不能确认”），仅 %d 条误命中" % (
             st["outOfScope"].get("soft", 0), st["outOfScope"].get("fail", 0))],
        ["单次作答时延", "%.2f ms" % st["latencyMs"], "离线检索，不含网络；手机端实测 < 5 ms"],
        ["拒答阈值", str(st["threshold"]), "低于该分数直接拒答，宁可不答也不猜"],
    ], widths=[3.4, 4.4, 8.8], size=9, align_center=[0])

    h1(doc, "二、来源可用性（联网实测）", "2")
    if hp:
        table(doc, ["项", "结果"], [
            ["校验时间", hp.get("checked_at", "—")],
            ["来源总数", str(hp.get("total", "—"))],
            ["可打开", "%s / %s" % (hp.get("ok", "—"), hp.get("total", "—"))],
            ["不可打开", str(hp.get("failed", "—"))],
            ["对应知识库版本", hp.get("kb_version", "—")],
        ], widths=[4.6, 12.0], size=9, align_center=[0])
        p(doc, "逐条结果见 data/kb_health.json。有链接打不开时，先看是不是政府网站临时维护；连续两次失败即下线该条，"
               "不拿“可能失效”的来源作答。", indent=True)
    else:
        p(doc, "尚未运行 tools/sync_kb.py。", indent=True)

    h1(doc, "三、主动写下的局限", "3")
    num_item(doc, 1, "**概念类问题会误命中数据条目**：问“红色旅游的定义”，命中的是“全国红色旅游人次”，"
                     "答案本身没错，但不是用户要的。下一版用向量检索补这一块。")
    num_item(doc, 2, "**只覆盖 50 条**：18 处旧址之外的点位（如钟山石窟、壶口以外的黄河点位）问不到。")
    num_item(doc, 3, "**同义问法集是我自己写的**：16 条，样本小，不代表真实游客的口语分布；"
                     "真实数据要等 20 人测试表回收后再补。")
    num_item(doc, 4, "**没有接大模型**：三种模式是模板改写，语言不如大模型自然；但事实层因此完全可控，"
                     "接入模型时只替换“怎么说”，不替换“说什么”。")

    h1(doc, "四、怎么复跑", "4")
    quote(doc, "node tools/selftest.js          # 输出 docs/selftest.json\n"
               "python tools/sync_kb.py         # 联网校验 26 个来源，输出 data/kb_health.json\n"
               "python build/build_kb.py        # 改完问答后重建知识库并升版本\n"
               "python run.py --port 8788       # 起服务，手机扫局域网地址")
    p(doc, "演示地址：%s" % public_url, size=9, color=GREY)

    doc.save(os.path.join(OUT, "08_自测报告.docx"))
    print("ok 08")


